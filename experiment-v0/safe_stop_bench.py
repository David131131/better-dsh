"""Observe original and strengthened stop policies on identical high trajectories."""

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
import getpass
from hashlib import sha256
import os
from pathlib import Path
from random import Random
import shutil
import tempfile
from threading import Event
import time

from bench import DEFAULT_DSH, PRICES, ROOT, ROUTE, execute, preflight, read_events, read_session, task_completed, write_json
from paired_bench import WIRE_BUCKETS, usage_rows
from paired_isolation import Relay, check_code, environment, isolation_probe, wrap
from safe_stop_cases import CASES


REPEATS = 3
PARALLEL = 4
TIMEOUT = 150
SEED = 20261113
RUNTIME = ROOT / ".runtime"
MODES = ("original", "strengthened", "natural")


def checks(case, path, scratch, names):
    return {name: check_code(getattr(case, name), path, scratch) for name in names}


def validate():
    version = preflight(DEFAULT_DSH)
    with tempfile.TemporaryDirectory(prefix="better-dsh-safe-check-") as raw:
        folder = Path(raw).resolve()
        isolation_probe(folder, RUNTIME)
        scratch = folder / "scratch"
        scratch.mkdir()
        for label, case in CASES.items():
            work = folder / label
            work.mkdir()
            for version_name, expected in (("original", (False,)),
                                           ("incomplete", (True, True, False, False)),
                                           ("reference", (True, True, True, True))):
                (work / "ledger.py").write_text(getattr(case, version_name))
                names = ("public", "smoke", "boundary", "hidden")[:len(expected)]
                outcome = checks(case, work, scratch, names)
                if tuple(v[0] for v in outcome.values()) != expected or any(
                    value[1].startswith("sandbox-exec:") for value in outcome.values()
                ):
                    raise ValueError((label, version_name, outcome))
            print(f"{label} 已确认旧实现失败、不完整补丁可误触发、参考实现全过。", flush=True)
    return version


def snapshot(path):
    # Each fixture has one in-scope source file. Ignore Python caches, which are
    # generated by tools, and decline to stop when any other file was introduced.
    target = path / "ledger.py"
    if target.is_symlink() or not target.is_file() or target.stat().st_size > 500_000:
        return None
    if any(p.name != "ledger.py" and (p.name != "__pycache__" or p.is_symlink() or not p.is_dir())
           for p in path.iterdir()):
        return None
    return target.read_bytes()


def metering(rows, valid):
    cost = usage_rows(rows, stopped=True, rejected=False)
    complete = valid and cost["complete"] and cost["requests_metered"] == len(rows)
    return {"tokens": cost["tokens"] if complete else None,
            "estimated_usd": cost["estimated_usd"] if complete else None,
            "requests": len(rows), "metered": complete,
            "finished_requests": cost["requests_metered"],
            "visible_estimated_usd": cost["estimated_usd"]}


def run(batch, label, repeat, key, cancel):
    if cancel.is_set():
        return
    case = CASES[label]
    folder = batch / f"{label}-{repeat}"
    folder.mkdir()
    workspace, inputs, scratch, home, scoring = (
        folder / p for p in ("workspace", "inputs", "scratch", "dsh-home", "scoring"))
    for p in (workspace, inputs, scratch, home, scoring):
        p.mkdir()
    (workspace / "ledger.py").write_text(case.original)
    for name in ("base.patch.yml", "high.patch.yml"):
        shutil.copyfile(ROOT / name, inputs / name)
    for name in ("public", "smoke"):
        (inputs / f"{name}.py").write_text("import sys\nsys.path.insert(0, '.')\n" + getattr(case, name))
    prompt = case.prompt + (
        "\n只修改当前目录的 ledger.py。可运行 python3 -B ../inputs/public.py 和 "
        "python3 -B ../inputs/smoke.py 验证。按题意自己检查其他边界，完成后简要说明。"
    )
    (folder / "prompt.txt").write_text(prompt)
    print(f"运行 {folder.name}", flush=True)
    started = time.monotonic()
    prior = case.original.encode()
    observed = {}
    transcript = []

    def capture():
        nonlocal prior
        if "strengthened" in observed or cancel.is_set():
            return False
        contents = snapshot(workspace)
        if contents is None or prior == contents:
            return False
        prior = contents
        # Run against an immutable copy outside the model-readable directories.
        (scoring / "ledger.py").write_bytes(contents)
        index = len(relay.rows)
        begin = time.monotonic()
        baseline = checks(case, scoring, scratch, ("public", "smoke"))
        base_time = time.monotonic()
        base_ok = all(passed for passed, _ in baseline.values())
        row = {"requests_before": index, "sha256": sha256(contents).hexdigest(),
               "checks": baseline, "baseline_seconds": round(base_time - begin, 4)}
        if base_ok and "original" not in observed:
            observed["original"] = {"requests": index, "elapsed_s": round(base_time - started, 3)}
            (folder / "original.py").write_bytes(contents)
        if base_ok:
            added = checks(case, scoring, scratch, ("boundary",))
            end = time.monotonic()
            row.update(added=added, added_seconds=round(end - base_time, 4))
            if added["boundary"][0]:
                observed["strengthened"] = {"requests": index, "elapsed_s": round(end - started, 3)}
                (folder / "strengthened.py").write_bytes(contents)
        transcript.append(row)
        return False

    with Relay(key, capture, lambda: TIMEOUT - (time.monotonic() - started)) as relay:
        env = environment(home, scratch)
        env.update(DEEPSEEK_API_KEY=relay.token,
                   DEEPSEEK_BASE_URL=f"http://127.0.0.1:{relay.port}/anthropic")
        argv = [DEFAULT_DSH, "--profile", "headless", "--patch", inputs / "base.patch.yml",
                "--patch", inputs / "high.patch.yml", "--json", "--permission-mode", "danger-full-access",
                "--approval-policy", "never", prompt]
        command = wrap(argv, (RUNTIME, inputs), (workspace, home, scratch), relay.port)
        exit_code, elapsed, interrupted = execute(command, workspace, env, folder, TIMEOUT, cancel)
    events, invalid_events = read_events(folder / "events.jsonl")
    sid = next((e.get("sessionId") for e in events if e["type"] == "session"), None)
    final = next((e for e in reversed(events) if e["type"] == "final"), {})
    session_path, session_events, invalid_session = read_session(home, sid)
    headers = [e["data"]["header"]["config"] for e in session_events if e["type"] == "request/header"]
    route_ok = bool(headers and relay.rows and not invalid_session) and all(
        (h.get("provider"), h.get("model")) == ROUTE and h.get("reasoningEffort") == "high" for h in headers
    ) and all(row["model"] == ROUTE[1] and row["effort"] == "high" for row in relay.rows)
    session_usage = [e["data"]["usage"] for e in session_events if e["type"] == "assistant/message"
                     and isinstance(e.get("data", {}).get("usage"), dict)]
    outcome = interrupted or ("completed" if task_completed(exit_code, final.get("reason")) else "dsh_error")
    timing = {
        "original": sum(r["baseline_seconds"] for r in transcript[:next(
            (i+1 for i,r in enumerate(transcript) if r["requests_before"] == observed.get("original", {}).get("requests")),
            len(transcript))]),
        "strengthened": sum(r.get("added_seconds", 0) for r in transcript),
    }
    final_source = snapshot(workspace)
    policies = {}
    for mode in MODES:
        point = observed.get(mode)
        selected = (folder / f"{mode}.py").read_bytes() if point else final_source
        if selected is None:
            grade = {"scope": (False, "最终产物超出单文件任务范围")}
        else:
            (scoring / "ledger.py").write_bytes(selected)
            grade = checks(case, scoring, scratch, ("public", "smoke", "hidden"))
        n = point["requests"] if point else len(relay.rows)
        usage = metering(relay.rows[:n], bool(route_ok and not invalid_events and not relay.rejected))
        if usage["metered"] and (len(session_usage) < n or usage["tokens"] != {
            k: sum(r.get(k, 0) for r in session_usage[:n]) for k in WIRE_BUCKETS
        }):
            usage.update(metered=False, tokens=None, estimated_usd=None)
        policies[mode] = {"checkpoint": bool(point), "elapsed_s": point["elapsed_s"] if point else elapsed,
                          "passed": bool(route_ok and (point or outcome == "completed")
                                         and all(passed for passed, _ in grade.values())),
                          "snapshot_passed": all(passed for passed, _ in grade.values()),
                          "checks": grade, **usage}
    row = {"case": label, "repeat": repeat, "high_verified": route_ok, "outcome": outcome, "exit_code": exit_code,
           "reason": final.get("reason"), "session_log": str(session_path.relative_to(folder)) if session_path else None,
           "policies": policies, "gate_timings": timing}
    write_json(folder / "result.json", row)
    write_json(folder / "relay.json", relay.rows)
    write_json(folder / "checkpoints.json", transcript)
    print(f"  {folder.name} {outcome} "
          + " ".join(f"{k}={'通过' if v['passed'] else '失败'}{'*' if v['checkpoint'] else ''}"
                     for k,v in policies.items()), flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    version = validate()
    if args.check:
        return 0
    key = os.environ.get("DEEPSEEK_API_KEY") or getpass.getpass("DeepSeek API Key（输入不显示）: ")
    if not key:
        parser.error("缺少 API Key")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    batch = Path(tempfile.mkdtemp(prefix=f"{stamp}-safe-stop-", dir=ROOT / "runs"))
    rng = Random(SEED)
    order = [(label, repeat) for repeat in range(1, REPEATS + 1)
             for label in rng.sample(list(CASES), len(CASES))]
    write_json(batch / "manifest.json", {
        "dsh_version": version, "model": ROUTE[1], "provider": ROUTE[0], "effort": "high",
        "parallel": PARALLEL, "timeout_s": TIMEOUT, "seed": SEED, "order": order,
        "titles": {key: c.title.strip() for key,c in CASES.items()}, "prices": PRICES,
        "source_sha256": {name: sha256((ROOT / name).read_bytes()).hexdigest() for name in (
            "safe_stop_bench.py", "safe_stop_cases.py", "paired_isolation.py", "paired_bench.py",
            "bench.py", "base.patch.yml", "high.patch.yml")},
    })
    print(f"结果目录：{batch}", flush=True)
    cancel = Event()
    pool = ThreadPoolExecutor(max_workers=PARALLEL)
    try:
        futures = [pool.submit(run, batch, label, repeat, key, cancel) for label,repeat in order]
        for future in as_completed(futures):
            future.result()
    except KeyboardInterrupt:
        cancel.set()
        return 130
    finally:
        pool.shutdown(wait=True, cancel_futures=cancel.is_set())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
